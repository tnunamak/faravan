export const V1_VERBS = ['app', 'host', 'run', 'apply', 'stop', 'join', 'job', 'circle', 'lending', 'mcp', 'doctor', 'diagnostics'];

const section = (title, lines) => lines.length ? ['', title + ':', ...lines.map(l => '  ' + l)] : [];
function render(entry) {
  const width = Math.max(0, ...(entry.options ?? []).map(([flag]) => flag.length)) + 2;
  return [entry.summary, '', 'Usage: ' + entry.usage,
    ...section('Notes', entry.notes ?? []),
    ...section('Options', (entry.options ?? []).map(([flag, text]) => flag.padEnd(width) + text)),
    ...(entry.actions ? section('Commands', Object.entries(entry.actions).map(([name, a]) => name.padEnd(10) + a.summary)) : []),
    '', 'Example:', '  ' + entry.example, ''].join('\n');
}

export function topLevelUsage() {
  const rows = [['run "<prompt>"', 'Run a coding job on a lender, from this git repository'], ['status', 'This device, your circles, lending and recent jobs'],
    ['apply JOB-ID', 'Put a finished job\'s changes on a new branch'], ['stop [JOB-ID]', COMMANDS.stop.summary], ['join INVITE', COMMANDS.join.summary],
    ['app', COMMANDS.app.summary], ['host', COMMANDS.host.summary], ['job', COMMANDS.job.summary], ['circle', COMMANDS.circle.summary], ['lending log', 'What went wrong with jobs this computer lent'],
    ['name', 'Show or set your name for invitations'], ['uninstall', 'Leave your circles and remove Faravan from this computer'], ['mcp', COMMANDS.mcp.summary], ['doctor', COMMANDS.doctor.summary],
    ['diagnostics export', 'Review and save a local support archive']];
  return ['Usage: faravan <command> [options]', '', 'Commands:', ...rows.map(([n, t]) => '  ' + n.padEnd(16) + t), '',
    'For agents and scripts: faravan ops list shows every operation; faravan <group> <verb> --json runs one',
    '(groups: status, lending, limits, agents, signin, jobs, approvals, circles, members, device, hosting, app, ...).',
    'Run faravan <command> --help (or faravan <command> <action> --help) for details.',
    'With no arguments, faravan opens the local app.', ''].join('\n');
}

/** Help text for `faravan <path...> --help`, or null if the command is unknown. */
export function helpFor(path) {
  const [verb, action] = path;
  if (!verb) return topLevelUsage();
  const entry = COMMANDS[verb];
  if (!entry) return null;
  if (action && entry.actions?.[action]) return render(entry.actions[action]);
  return render(entry);
}
export const wantsHelp = argv => argv.includes('--help') || argv.includes('-h');
