import {test,expect} from '@playwright/test';
import {startHarness} from './lib.mjs';
let harness;
test.beforeAll(async()=>{harness=await startHarness();});
test.afterAll(async()=>{await harness?.stop();});
test('Home waits for circles and shared jobs, then keeps jobs across navigation',async({page})=>{
 const circle={id:'shared',name:'Weekend projects',origin:'http://fixture',owned:true};
 let releaseCircles,releaseJobs;
 const circles=new Promise(resolve=>{releaseCircles=resolve;}),jobs=new Promise(resolve=>{releaseJobs=resolve;});
 await page.route('**/api/home',r=>r.fulfill({json:{lending:{enabled:false,circle:'shared',status:'idle'},circles:[circle]}}));
 await page.route('**/api/circles',async r=>{await circles;await r.fulfill({json:[circle]});});
 await page.route('**/api/agents',r=>r.fulfill({json:[]}));
 await page.route('**/api/approvals',r=>r.fulfill({json:[]}));
 await page.route('**/api/jobs',async r=>{await jobs;await r.fulfill({json:[{job_digest:'returned',status:'Finished',local:{title:'Fix the parser'},circle,waitingTiming:{submittedAt:new Date().toISOString()}}]});});
 await page.route('**/api/jobs/*/changes?*',r=>r.fulfill({json:{format:'diff',files:[],diff:''}}));
 await page.goto((await harness.link('lender'))+'#/home');
 await expect(page.getByLabel('Loading jobs',{exact:true})).toBeVisible();
 await expect(page.getByText('Start a circle',{exact:true})).toHaveCount(0);
 await expect(page.getByText('No jobs in motion.',{exact:true})).toHaveCount(0);
 releaseCircles();
 await expect(page.locator('.home-loading')).not.toHaveCount(0);
 await expect(page.getByText('Start a circle',{exact:true})).toHaveCount(0);
 releaseJobs();
 await expect(page.locator('.result-card')).toContainText('Fix the parser');
 await page.evaluate(()=>{location.hash='#/settings';});
 await expect(page.getByRole('heading',{name:'You',exact:true})).toBeVisible();
 await page.evaluate(()=>{location.hash='#/home';});
 await expect(page.locator('.result-card')).toContainText('Fix the parser');
 await expect(page.getByLabel('Loading jobs',{exact:true})).toHaveCount(0);
});
