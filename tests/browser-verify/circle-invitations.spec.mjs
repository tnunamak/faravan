import {test,expect} from '@playwright/test';
import {mkdir} from 'node:fs/promises';
import {join} from 'node:path';
import {startHarness} from './lib.mjs';
let harness;
const screenshots=process.env.CIRCLES_INVITATIONS_SCREENSHOTS??'test-artifacts/browser-verify/circle-invitations';
test.beforeAll(async()=>{harness=await startHarness();});
test.afterAll(async()=>{await harness?.stop();});
const circle={id:'invitation-circle',name:'Weekend projects',origin:'http://fixture',owned:true};
const row={id:'invitation-a',state:'issued',createdAt:'2026-10-20T12:00:00Z',expiresAt:'2026-10-21T12:00:00Z',approved:2,waiting:1,unconfirmed:0,maxUses:10};
for(const size of [{width:1440,height:900},{width:390,height:844}])for(const theme of ['light','dark']) {
  test(`invitation controls ${size.width} ${theme}`,async({page})=>{
    let revoked=false;const requests=[];
    await page.setViewportSize(size);
    await page.emulateMedia({colorScheme:theme});
    await page.addInitScript(theme=>localStorage.setItem('faravan-theme',theme),theme);
    await page.route('**/api/circles',r=>r.fulfill({json:[circle]}));
    await page.route('**/api/devices',r=>r.fulfill({json:{fingerprint:'self',name:'My laptop',ownerName:'Maya',circles:[{circle:circle.id,members:[{key_id:'self',device_name:'My laptop'}]}]}}));
    await page.route('**/api/circles/'+circle.id+'/invitations',r=>r.fulfill({json:[{...row,state:revoked?'revoked':'waiting',waiting:revoked?0:1}]}));
    await page.route('**/api/circles/'+circle.id+'/people',r=>r.fulfill({json:[]}));
    await page.route('**/api/circles/'+circle.id+'/approvals',r=>r.fulfill({json:[]}));
    await page.route('**/api/circles/'+circle.id+'/invitations/revoke',r=>{revoked=true;requests.push(r.request().postDataJSON());return r.fulfill({json:{revoked:true}});});
    await page.route('**/api/circles/'+circle.id+'/invite',r=>{requests.push(r.request().postDataJSON());return r.fulfill({json:{invite:'https://circle.example/i/abcdefghij#test-only-link'}});});
    await page.goto((await harness.link('owner'))+'#/circle/'+circle.id);
    await page.getByRole('tab',{name:'Invitations',exact:true}).click();
    await expect(page.getByText('Waiting for approval',{exact:true})).toHaveClass(/pill/);
    await expect(page.getByRole('heading',{name:'Group chat',exact:true})).toBeVisible();
    await expect(page.getByRole('heading',{name:'Invitations',exact:true})).toHaveCount(0);
    await expect(page.getByRole('button',{name:'Refresh invitations',exact:true})).toHaveClass(/btn-secondary/);
    expect(await page.locator('[aria-label="Invitation history"]').innerText()).not.toMatch(/\d+:\d+:\d+/);
    await expect(page.getByText('2 approved · 1 waiting · Up to 10 computers')).toBeVisible();
    await page.getByRole('button',{name:'Revoke invitation',exact:true}).click();
    await expect(page.getByRole('dialog')).toContainText('Computers already approved keep their access');
    await page.getByRole('dialog').getByRole('button',{name:'Revoke invitation',exact:true}).click();
    await expect(page.getByText('Revoked',{exact:true})).toBeVisible();
    expect(requests[0]).toEqual({inviteId:row.id});
    await mkdir(screenshots,{recursive:true});
    await page.screenshot({path:join(screenshots,`ledger-${size.width}-${theme}.png`),fullPage:true});
    await page.getByRole('button',{name:'Invite someone',exact:true}).click();
    await page.getByLabel('Invitation for').selectOption('group');
    await expect(page.getByText(/Anyone with this link can join automatically/)).toBeVisible();
    await page.getByRole('button',{name:'Create invitation',exact:true}).click();
    await expect(page.getByLabel('Invitation link')).toBeVisible();
    expect(requests[1]).toEqual({preset:'group'});
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    await mkdir(screenshots,{recursive:true});
    await page.screenshot({path:join(screenshots,`invitations-${size.width}-${theme}.png`),fullPage:true});
  });
}
test('focusing the circle name protects edits from a late owner-name prefill',async({page})=>{
  let release;const held=new Promise(r=>{release=r;});
  await page.route('**/api/devices',async r=>{await held;await r.fulfill({json:{name:'Laptop',ownerName:'Late owner',circles:[]}});});
  await page.route('**/api/hosting',r=>r.fulfill({json:{configured:false}}));
  await page.goto((await harness.link('owner'))+'#/circles/host');
  const input=page.getByLabel('Circle name');
  await input.focus();
  const response=page.waitForResponse('**/api/devices');release();await response;
  await page.waitForTimeout(100);
  await expect(page.getByText('Start a circle on this computer',{exact:true})).toBeVisible();
  await expect(input).toHaveValue('');
  await input.fill('Weekend projects');
  await expect(input).toHaveValue('Weekend projects');
});
